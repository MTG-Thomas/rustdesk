//! Preserve the pinned Sciter compiler while modern Cargo resolves metadata.
//! A native wrapper avoids cmd.exe's 8191-character argument limit.
use std::{
    env,
    ffi::OsString,
    io,
    process::{Command, ExitCode},
};

fn compiler_arguments(arguments: impl IntoIterator<Item = OsString>) -> io::Result<Vec<OsString>> {
    let mut result = Vec::new();
    let mut arguments = arguments.into_iter();
    while let Some(argument) = arguments.next() {
        if argument == "--check-cfg" {
            // Old Cargo supplied none of these generated declarations; the 2023
            // compiler cannot parse the syntax generated by Cargo 1.90.
            if arguments.next().is_none() {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidInput,
                    "missing check-cfg declaration",
                ));
            }
        } else {
            result.push(argument);
        }
    }
    Ok(result)
}

fn main() -> io::Result<ExitCode> {
    let mut arguments = env::args_os().skip(1);
    let compiler = arguments
        .next()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "missing compiler"))?;
    let status = Command::new(compiler)
        .args(compiler_arguments(arguments)?)
        .status()?;
    Ok(if status.success() {
        ExitCode::SUCCESS
    } else {
        ExitCode::from(
            status
                .code()
                .and_then(|code| u8::try_from(code).ok())
                .unwrap_or(1),
        )
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn long_arguments_preserve_explicit_lints_paths_and_feature_flags() {
        let mut input = vec![
            OsString::from("-D"),
            OsString::from("warnings"),
            OsString::from("path with spaces/日本語.rs"),
        ];
        for i in 0..1000 {
            input.extend([
                OsString::from("--cfg"),
                OsString::from(format!("feature=\"Windows_{i}\"")),
            ]);
        }
        let expected = input.clone();
        input.extend([
            OsString::from("--check-cfg"),
            OsString::from("cfg(feature, values(\"a\"))"),
        ]);
        assert!(input.iter().map(|arg| arg.len()).sum::<usize>() > 8191);
        assert_eq!(compiler_arguments(input).unwrap(), expected);
        assert!(compiler_arguments([OsString::from("--check-cfg")]).is_err());
    }
}
